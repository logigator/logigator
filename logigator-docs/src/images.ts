/**
 * Documentation screenshots per language, keyed by the destination authored in
 * that language's markdown; every import resolves to the consuming build's
 * cache-busted URL, so rendering swaps the authored destination for the hashed
 * one.
 *
 * These are shared where the markdown is not: both apps emit a picture through
 * a `file` loader, so one import map serves the editor's viewer and the
 * website's pages alike.
 *
 * Board screenshots carry no interface text and are captured once in English;
 * only localized chrome is shot per language, and `docImages` falls back per
 * key, so a language lists exactly the pictures that differ.
 *
 * Every picture is lossless WebP — animated for the step-throughs — which is
 * the capture tool's only output format.
 *
 * Generated by `logigator-editor/tools/screenshots` — add a picture by
 * capturing it and running the `docs` target, which writes this file.
 */
export const DOC_IMAGES: Readonly<
  Record<string, Readonly<Record<string, DocImage>>>
> = { en, de, fr, es };

/** A language's screenshots: its own where it has them, English elsewhere. */
export function docImages(lang: string): Readonly<Record<string, DocImage>> {
  const localized = DOC_IMAGES[lang];
  return localized ? { ...DOC_IMAGES['en'], ...localized } : DOC_IMAGES['en'];
}
