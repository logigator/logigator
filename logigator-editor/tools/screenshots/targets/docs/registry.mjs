/**
 * Writes `logigator-docs/src/images.ts` from what is on disk under
 * `logigator-docs/src/pages/<lang>/images/`. The runner calls this once the
 * captures are written.
 *
 * Which pictures a language has is decided by the run, so the registry follows
 * the folders rather than a hand-kept list.
 */
import path from 'node:path';
import { LOCALES } from '../../lib/config.mjs';
import {
  camelCase,
  captureFiles,
  importLines,
  writeGenerated
} from '../../lib/registry.mjs';

/**
 * Writes the registry for the tree at `dest` — the docs package's own root, so
 * the file lands at `<dest>/src/images.ts`, beside the `pages/` it describes.
 *
 * Refused when no language has a capture, for the same reason the runner
 * refuses a target with no shots: an empty map is a valid file that resolves
 * every picture in the documentation to nothing, and it is tracked, so the
 * harm commits. Reaching here with nothing to describe means the out-dir is
 * not the tree the run captured into.
 */
export function writeRegistry(dest) {
  const root = path.resolve(dest, 'src');
  const registry = path.join(root, 'images.ts');

  const groups = LOCALES.map((lang) => ({
    lang,
    files: captureFiles(path.join(root, 'pages', lang, 'images'))
  })).filter((group) => group.files.length > 0);

  if (groups.length === 0) {
    throw new Error(
      `no captures under ${path.join(root, 'pages')} — the out-dir has to be ` +
        'the logigator-docs package this run captured into'
    );
  }

  // `menu-bar.webp` in `de` → `menuBarDe`: the picture and the language that
  // has it, since the same shot is a file in each.
  const ident = (lang, file) =>
    `${camelCase(path.parse(file).name)}${lang[0].toUpperCase()}${lang.slice(1)}`;

  const imports = groups
    .flatMap(({ lang, files }) =>
      importLines(
        files,
        registry,
        path.join(root, 'pages', lang, 'images'),
        (file) => ident(lang, file)
      )
    )
    .join('\n');

  const maps = groups
    .map(({ lang, files }) => {
      const entries = files
        .map((file) => `  './images/${file}': ${ident(lang, file)}`)
        .join(',\n');
      return `const ${lang}: Readonly<Record<string, string>> = {\n${entries}\n};`;
    })
    .join('\n\n');

  const source = `${imports}

/** One language's screenshots, keyed by the destination the markdown uses. */
${maps}

/**
 * Documentation screenshots per language, keyed by the destination authored in
 * that language's markdown; every import resolves to the consuming build's
 * cache-busted URL, so rendering swaps the authored destination for the hashed
 * one.
 *
 * These are shared where the markdown is not: both apps emit a picture through
 * a \`file\` loader, so one import map serves the editor's viewer and the
 * website's pages alike.
 *
 * Board screenshots carry no interface text and are captured once in English;
 * only localized chrome is shot per language, and \`docImages\` falls back per
 * key, so a language lists exactly the pictures that differ.
 *
 * Every picture is lossless WebP — animated for the step-throughs — which is
 * the capture tool's only output format.
 *
 * Generated by \`logigator-editor/tools/screenshots\` — add a picture by
 * capturing it and running the \`docs\` target, which writes this file.
 */
export const DOC_IMAGES: Readonly<
  Record<string, Readonly<Record<string, string>>>
> = { ${groups.map((group) => group.lang).join(', ')} };

/** A language's screenshots: its own where it has them, English elsewhere. */
export function docImages(lang: string): Readonly<Record<string, string>> {
  const localized = DOC_IMAGES[lang];
  return localized ? { ...DOC_IMAGES['en'], ...localized } : DOC_IMAGES['en'];
}
`;

  return writeGenerated(
    registry,
    source,
    groups.map((group) => `${group.lang}: ${group.files.length}`).join('  ')
  );
}
