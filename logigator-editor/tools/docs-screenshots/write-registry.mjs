#!/usr/bin/env node
/**
 * Rewrites `logigator-docs/src/images.ts` from what is on disk under
 * `logigator-docs/src/pages/<lang>/images/`. Run it after copying a capture
 * into the tree.
 *
 *   node tools/docs-screenshots/write-registry.mjs
 *
 * Which pictures a language has is decided by the run, so the registry follows
 * the folders rather than a hand-kept list.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES } from './config.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.join(here, '..', '..', '..', 'logigator-docs', 'src');
const REGISTRY = path.join(DOCS, 'images.ts');

/** `menu-bar.png` in `de` → `menuBarDe`, the import name for one picture. */
function ident(lang, file) {
  const name = path
    .parse(file)
    .name.replace(/-([a-z0-9])/g, (_, char) => char.toUpperCase());
  return `${name}${lang[0].toUpperCase()}${lang.slice(1)}`;
}

const groups = LOCALES.map((lang) => {
  const dir = path.join(DOCS, 'pages', lang, 'images');
  const files = fs.existsSync(dir)
    ? fs
        .readdirSync(dir)
        .filter((file) => /\.(png|gif)$/.test(file))
        .sort()
    : [];
  return { lang, files };
}).filter((group) => group.files.length > 0);

const imports = groups
  .flatMap(({ lang, files }) =>
    files.map(
      (file) =>
        `import ${ident(lang, file)} from './pages/${lang}/images/${file}';`
    )
  )
  .join('\n');

const maps = groups
  .map(({ lang, files }) => {
    const entries = files
      .map((file) => `  './images/${file}': ${ident(lang, file)}`)
      .join(',\n');
    return `const ${lang}: Readonly<Record<string, string>> = {\n${entries}\n};`;
  })
  .join('\n\n');

const source = `${imports}

/** One language's screenshots, keyed by the destination the markdown uses. */
${maps}

/**
 * Documentation screenshots per language, keyed by the destination authored in
 * that language's markdown; every import resolves to the consuming build's
 * cache-busted URL, so rendering swaps the authored destination for the hashed
 * one.
 *
 * These are shared where the markdown is not: both apps emit a picture through
 * a \`file\` loader, so one import map serves the editor's viewer and the
 * website's pages alike.
 *
 * Board screenshots carry no interface text and are captured once in English;
 * only localized chrome is shot per language, and \`docImages\` falls back per
 * key, so a language lists exactly the pictures that differ.
 *
 * Generated by \`logigator-editor/tools/docs-screenshots/write-registry.mjs\` —
 * add a picture by dropping it under \`pages/<lang>/images/\` and running that.
 */
export const DOC_IMAGES: Readonly<
  Record<string, Readonly<Record<string, string>>>
> = { ${groups.map((group) => group.lang).join(', ')} };

/** A language's screenshots: its own where it has them, English elsewhere. */
export function docImages(lang: string): Readonly<Record<string, string>> {
  const localized = DOC_IMAGES[lang];
  return localized ? { ...DOC_IMAGES['en'], ...localized } : DOC_IMAGES['en'];
}
`;

fs.writeFileSync(REGISTRY, source);
console.log(
  `${groups.map((group) => `${group.lang}: ${group.files.length}`).join('  ')} → ${path.relative(process.cwd(), REGISTRY)}`
);
